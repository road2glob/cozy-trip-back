// Builds the MCP Apps card into one self-contained HTML string (inline CSS + inline JS; the default
// MCP Apps CSP allows nothing else) and writes it as a TypeScript module the Worker imports.
// Usage: npm run build:ui   (the test suite fails if the committed output is stale)
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const path = (p) => fileURLToPath(new URL(p, root));
export const OUTPUT = path("src/ui/cardHtml.generated.ts");

export async function buildCardHtml() {
  const result = await build({
    entryPoints: [path("ui/main.ts")],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2022"],
    minify: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
    logLevel: "silent",
  });
  // A literal "</script" inside the bundle would end the inline script early.
  const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  // Normalize line endings so a CRLF checkout (git autocrlf on Windows) builds the same bytes.
  const css = readFileSync(path("ui/cards.css"), "utf8").replace(/\r\n/g, "\n");
  const template = readFileSync(path("ui/template.html"), "utf8").replace(/\r\n/g, "\n");
  return template.replace("/*__CSS__*/", () => css).replace("/*__JS__*/", () => js);
}

export function moduleSource(html) {
  return `// Generated by scripts/build-ui.mjs from ui/. Do not edit by hand; run npm run build:ui.\nexport const CARD_HTML = ${JSON.stringify(html)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const html = await buildCardHtml();
  writeFileSync(OUTPUT, moduleSource(html), "utf8");
  console.log(`Wrote ${OUTPUT} (${Math.round(html.length / 1024)} KiB of HTML)`);
}
